/* tensile_report core: Phase 0 proof page (exercises text, wrapping, table, chart, footer). */
#include <math.h>
#include <stdio.h>
#include <string.h>

#include "tr_internal.h"

#define MARGIN_L 72.0
#define MARGIN_R 72.0
#define MARGIN_T 36.0
#define MARGIN_B 36.0
#define CONTENT_W (TR_PAGE_W - MARGIN_L - MARGIN_R)

static void heading(tr_doc_t *doc, double *y, const char *text)
{
    *y -= 16;
    tr_set_fill_rgb(doc, tr_rgb_hex(0x424242));
    tr_text(doc, MARGIN_L, *y, TR_FONT_HELVETICA_BOLD, 12, text);
    *y -= 6;
}

int tr_phase0_proof(tr_doc_t *doc, const tr_test_row_t *tests, int n, int64_t generated_utc,
                    int tz_offset_min)
{
    if (!doc) {
        return TR_ERR_ARG;
    }
    if (doc->err != TR_OK) {
        return doc->err;
    }
    if (!tests || n <= 0 || n > 64) {
        return tr__fail(doc, TR_ERR_ARG);
    }

    /* statistics (sample standard deviation, as the desktop app) */
    double sum = 0, mn = tests[0].peak_kn, mx = tests[0].peak_kn;
    for (int i = 0; i < n; i++) {
        sum += tests[i].peak_kn;
        mn = tests[i].peak_kn < mn ? tests[i].peak_kn : mn;
        mx = tests[i].peak_kn > mx ? tests[i].peak_kn : mx;
    }
    double mean = sum / n, ss = 0;
    for (int i = 0; i < n; i++) {
        ss += (tests[i].peak_kn - mean) * (tests[i].peak_kn - mean);
    }
    double sd = n > 1 ? sqrt(ss / (n - 1)) : 0.0;
    double lo3 = mean - 3 * sd, hi3 = mean + 3 * sd;

    if (tr_page_begin(doc) != TR_OK) {
        return doc->err;
    }
    char buf[192];
    double y = TR_PAGE_H - MARGIN_T;

    /* header */
    y -= 18;
    tr_set_fill_rgb(doc, tr_rgb_hex(0x2196F3));
    tr_text_aligned(doc, TR_PAGE_W / 2, y, TR_ALIGN_CENTER, TR_FONT_HELVETICA_BOLD, 18,
                    "Tensile Testing Statistical Analysis Report");
    y -= 17;
    char when[24];
    tr_format_datetime(when, sizeof when, generated_utc, tz_offset_min);
    snprintf(buf, sizeof buf, "Generated: %s", when);
    tr_set_fill_rgb(doc, tr_rgb_hex(0x000000));
    tr_text_aligned(doc, TR_PAGE_W / 2, y, TR_ALIGN_CENTER, TR_FONT_HELVETICA, 10, buf);
    y -= 13;
    tr_set_fill_rgb(doc, tr_rgb_hex(0x808080));
    tr_text_aligned(doc, TR_PAGE_W / 2, y, TR_ALIGN_CENTER, TR_FONT_HELVETICA, 9,
                    "TensileOS HMI \xE2\x80\x93 Phase 0 PDF writer proof");

    /* wrapped paragraph */
    heading(doc, &y, "About This Page");
    static const char para[] =
        "This page was generated by the tensile_report streaming PDF writer that runs on the "
        "TensileOS HMI. It uses the base-14 Helvetica fonts with WinAnsi encoding, vector "
        "graphics and an uncompressed PDF 1.4 cross-reference table, and it is written straight "
        "to the SD card \xE2\x80\x94 only the object offsets are kept in RAM. Peak forces come "
        "from the five golden test files of 2026-01-20; the chart shows every test with the "
        "mean and the \xC2\xB1" "3 sigma bounds. Values are in kN with three decimals, "
        "matching the desktop \xE2\x80\x9C" "Export Report\xE2\x80\x9D output.";
    tr_set_fill_rgb(doc, tr_rgb_hex(0x000000));
    int lines = tr_text_box(doc, MARGIN_L, y, CONTENT_W, TR_FONT_HELVETICA, 10, 13,
                            TR_ALIGN_LEFT, para, 0);
    if (lines > 0) {
        y -= lines * 13;
    }
    y -= 4;
    snprintf(buf, sizeof buf,
             "Tests: %d     Mean: %.3f kN     s: %.3f kN     3-Sigma Range: %.3f to %.3f kN     "
             "3-Sigma MBS: %.3f kN",
             n, mean, sd, lo3, hi3, lo3);
    y -= 11;
    tr_set_fill_rgb(doc, tr_rgb_hex(0xFF5722));
    tr_text_aligned(doc, TR_PAGE_W / 2, y, TR_ALIGN_CENTER, TR_FONT_HELVETICA_BOLD, 8.5, buf);

    /* results table: same columns and widths as the desktop report */
    heading(doc, &y, "Individual Test Results");
    static const double col_w[6] = {21.6, 54, 172.8, 64.8, 50.4, 64.8};
    static const char *const hdr[6] = {"#", "Test Name", "Project", "Technician", "Peak (kN)",
                                       "Deviation"};
    tr_table_t t;
    memset(&t, 0, sizeof t);
    tr_table_defaults(&t);
    t.ncols = 6;
    t.col_w = col_w;
    t.header = hdr;
    double tw = 0;
    for (int i = 0; i < 6; i++) {
        tw += col_w[i];
    }
    t.x = MARGIN_L + (CONTENT_W - tw) / 2;
    t.y_top = TR_PAGE_H - MARGIN_T;
    t.y_bottom = MARGIN_B + 30;
    tr_table_header(doc, &t, &y);
    for (int i = 0; i < n; i++) {
        char idx[8], peak[24], dev[24];
        snprintf(idx, sizeof idx, "%d", i + 1);
        snprintf(peak, sizeof peak, "%.3f", tests[i].peak_kn);
        snprintf(dev, sizeof dev, "%+.3f", tests[i].peak_kn - mean);
        const char *cells[6] = {idx, tests[i].name, tests[i].project, tests[i].technician, peak,
                                dev};
        tr_table_row(doc, &t, cells, &y);
    }

    /* chart: 6 x 2.6 in like the desktop report, vector instead of raster */
    heading(doc, &y, "Peak Force Distribution");
    const char *labels[64];
    double values[64];
    for (int i = 0; i < n; i++) {
        labels[i] = tests[i].name;
        values[i] = tests[i].peak_kn;
    }
    tr_chart_cfg_t cc;
    memset(&cc, 0, sizeof cc);
    cc.w = 432;
    cc.h = 187.2;
    cc.x = MARGIN_L + (CONTENT_W - cc.w) / 2;
    cc.y = y - cc.h;
    cc.title = "Peak Forces with Mean and 3-Sigma Bounds";
    cc.x_label = "Test";
    cc.y_label = "Peak Force (kN)";
    cc.y_min = lo3 < 0 ? lo3 : 0;
    cc.y_max = (hi3 > mx ? hi3 : mx);
    cc.legend_w = 78;
    cc.x_label_angle = 45;
    cc.grid = 1;
    tr_chart_t ch;
    tr_chart_begin(doc, &cc, &ch);
    tr_chart_bars(doc, &ch, values, labels, n, tr_rgb_hex(0x64B5F6), "Peak");
    char mean_s[32], hi_s[32], lo_s[32];
    snprintf(mean_s, sizeof mean_s, "Mean %.3f", mean);
    snprintf(hi_s, sizeof hi_s, "+3 sigma %.3f", hi3);
    snprintf(lo_s, sizeof lo_s, "-3 sigma %.3f", lo3);
    tr_chart_hline(doc, &ch, mean, tr_rgb_hex(0x4CAF50), 2, TR_LINE_DASHED, "Mean", mean_s);
    tr_chart_hline(doc, &ch, hi3, tr_rgb_hex(0xFF5722), 2, TR_LINE_DOTTED, "+3 sigma", hi_s);
    tr_chart_hline(doc, &ch, lo3, tr_rgb_hex(0xFF5722), 2, TR_LINE_DOTTED, "-3 sigma", lo_s);
    tr_chart_end(doc, &ch);

    /* footer */
    tr_set_fill_rgb(doc, tr_rgb_hex(0x808080));
    tr_text_aligned(doc, TR_PAGE_W / 2, 36, TR_ALIGN_CENTER, TR_FONT_HELVETICA, 9,
                    "Created via TensileOS");
    snprintf(buf, sizeof buf, "Page %lu of %lu", (unsigned long)doc->page_count,
             (unsigned long)doc->page_count);
    tr_text_aligned(doc, TR_PAGE_W - MARGIN_R, 36, TR_ALIGN_RIGHT, TR_FONT_HELVETICA, 9, buf);
    return tr_page_end(doc);
}
